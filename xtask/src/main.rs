//! Maintainer tasks for giant-squid. Run them with `cargo xtask <task>` (an
//! alias in `.cargo/config.toml`):
//!
//! * `regen-openapi`: regenerates `src/mwa_asvo/api/openapi.rs` from
//!   `src/mwa_asvo/api/openapi-schema.json`, using typify
//!   (<https://github.com/oxidecomputer/typify>). Run it when the schema has
//!   changed (`tools/generate_openapi.sh` does it after it downloads the
//!   schema), then review and commit the result. The CI job
//!   `openapi-drift-check` runs it again and fails if the file changes. Do not
//!   run `cargo fmt` or `cargo clippy --fix` on the generated file: it is
//!   committed as prettyplease writes it.
//!
//! The task also writes the command-line help texts of the request bodies
//! (the schema's `x-cmd-help`) into `openapi.rs`: see [`cmd_help_source`].
//!
//! The generator is here, and not in the build script of the library, so that
//! a normal build does not need typify, schemars, syn or prettyplease.

use std::process::ExitCode;

use std::fs;
use std::path::Path;

use schemars::schema::{InstanceType, SchemaObject};
use typify::{TypeSpace, TypeSpaceImpl, TypeSpacePatch, TypeSpaceSettings};

/// The schema that the types are generated from, relative to the workspace root.
const SCHEMA_PATH: &str = "src/mwa_asvo/api/openapi-schema.json";
/// The generated file, relative to the workspace root.
const OUTPUT_PATH: &str = "src/mwa_asvo/api/openapi.rs";
/// The Rust type for a schema `date-time` string. typify's own choice
/// is `chrono::DateTime<Utc>`; giant-squid uses jiff instead (chrono is
/// soft-deprecated). Every MWA ASVO time is UTC, so a `Timestamp` fits.
const DATE_TIME_TYPE: &str = "::jiff::Timestamp";
/// The JSON Schema format that `DATE_TIME_TYPE` replaces.
const DATE_TIME_FORMAT: &str = "date-time";
/// The derive added to every generated type.
const ALL_TYPES_DERIVE: &str = "PartialEq";
/// The schema's job type code, and the derives it gets as well.
const JOB_TYPE: &str = "JobType";
const JOB_TYPE_DERIVES: [&str; 3] = ["Copy", "Eq", "Hash"];

// No embedded generation timestamp on purpose: a timestamp here would make the
// file "change" (and the CI drift check fail) even when the schema has not,
// which would defeat the point of that check.
const HEADER: &str = "\
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at http://mozilla.org/MPL/2.0/.

//
// The code in this file is AUTOGENERATED by `cargo xtask regen-openapi` (see
// xtask/src/main.rs), from src/mwa_asvo/api/openapi-schema.json.
// Manual edits or modifications will be lost next time it is generated!
//
";

/// The Rust source of the two version constants of `openapi.rs`: the
/// version of the OpenAPI specification (the `openapi` key of the schema
/// file) and the version of the MWA ASVO API (`info.version`). Both are
/// written by tools/generate_openapi.sh from the server's document.
fn versions_source(schema_file: &str) -> String {
    let document: serde_json::Value = serde_json::from_str(schema_file)
        .unwrap_or_else(|e| panic!("failed to parse {SCHEMA_PATH} as JSON: {e}"));
    let version = |value: Option<&serde_json::Value>, key: &str| {
        value
            .and_then(serde_json::Value::as_str)
            .unwrap_or_else(|| panic!("{SCHEMA_PATH} has no {key}: run tools/generate_openapi.sh"))
            .to_string()
    };
    let openapi = version(document.get("openapi"), "openapi");
    let api = version(document.pointer("/info/version"), "info.version");
    format!(
        "/// The version of the OpenAPI specification that the MWA ASVO API's document is written in.\n\
         pub const OPENAPI_VERSION: &str = {openapi:?};\n\
         /// The version of the MWA ASVO API that this file was generated from.\n\
         pub const MWA_ASVO_API_VERSION: &str = {api:?};\n\n"
    )
}

/// The schema key of the command-line help text of a field.
const CMD_HELP_KEY: &str = "x-cmd-help";
/// The name of the generated macro that gives a help text as a string
/// literal.
const CMD_HELP_MACRO: &str = "cmd_help_text";

/// The help texts of one schema type.
#[derive(PartialEq, Eq, PartialOrd, Ord)]
struct TypeHelp {
    /// The name of the type's module of help texts, for example
    /// `image_from_job_params`.
    module: String,
    /// The schema name of the type, for example `ImageFromJobParams`.
    type_name: String,
    /// `(field, text)` for each field with a help text, in name order.
    fields: Vec<(String, String)>,
}

/// `ImageFromJobParams` as `image_from_job_params`: the name of the module
/// of a request body's help texts.
fn snake_case(name: &str) -> String {
    let mut snake = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                snake.push('_');
            }
            snake.push(c.to_ascii_lowercase());
        } else {
            snake.push(c);
        }
    }
    snake
}

/// The Rust source of the command-line help texts: the `x-cmd-help` of each
/// field of each schema type that has one, with the spaces at its start and
/// end removed and otherwise as the schema has it.
///
/// The source is a macro, `cmd_help_text!(<type>, <field>)`, that gives the
/// text as a string literal (so that it can be used in `concat!`, for
/// example in a doc comment), and a module `cmd_help` with one module for
/// each schema type and one constant for each field (for example
/// `cmd_help::imaging_job_params::UV_MIN`). The types and fields are in
/// name order, so the output does not depend on the order of the schema
/// file.
fn cmd_help_source(schema_file: &str) -> String {
    let document: serde_json::Value = serde_json::from_str(schema_file)
        .unwrap_or_else(|e| panic!("failed to parse {SCHEMA_PATH} as JSON: {e}"));
    let definitions = document
        .get("definitions")
        .and_then(serde_json::Value::as_object)
        .unwrap_or_else(|| panic!("{SCHEMA_PATH} has no definitions"));

    // Each type with a help text, in module order.
    let mut types: Vec<TypeHelp> = Vec::new();
    for (type_name, definition) in definitions {
        let Some(properties) = definition
            .get("properties")
            .and_then(serde_json::Value::as_object)
        else {
            continue;
        };
        let mut fields: Vec<(String, String)> = properties
            .iter()
            .filter_map(|(field, property)| {
                property
                    .get(CMD_HELP_KEY)
                    .and_then(serde_json::Value::as_str)
                    .map(|text| (field.clone(), text.trim().to_string()))
            })
            .collect();
        if fields.is_empty() {
            continue;
        }
        fields.sort();
        types.push(TypeHelp {
            module: snake_case(type_name),
            type_name: type_name.clone(),
            fields,
        });
    }
    types.sort();

    let mut source = format!(
        "/// The command-line help text (the schema's `{CMD_HELP_KEY}`) of the field `<field>` of the\n\
         /// request body `<type>`, as a string literal: `{CMD_HELP_MACRO}!(imaging_job_params, uv_min)`.\n\
         /// A string literal can be used in `concat!`, for example in a doc comment. The macro is\n\
         /// in scope in the modules declared after this one (`#[macro_use]` on the modules\n\
         /// above it): a `use` of it cannot be resolved in the doc attribute of a `#[pyclass]`.\n\
         macro_rules! {CMD_HELP_MACRO} {{\n"
    );
    for TypeHelp { module, fields, .. } in &types {
        for (field, text) in fields {
            source.push_str(&format!("    ({module}, {field}) => {{ {text:?} }};\n"));
        }
    }
    source.push_str("}\n\n");

    source.push_str(&format!(
        "/// The command-line help texts (the schema's `{CMD_HELP_KEY}`) of the request bodies: one\n\
         /// module for each body, and one constant for each field.\n\
         pub mod cmd_help {{\n"
    ));
    for TypeHelp {
        module,
        type_name,
        fields,
    } in &types
    {
        source.push_str(&format!(
            "    /// The help texts of the fields of `{type_name}`.\n    pub mod {module} {{\n"
        ));
        for (field, _) in fields {
            let constant = field.to_uppercase();
            source.push_str(&format!(
                "        /// The help text of `{field}`.\n        pub const {constant}: &str = {CMD_HELP_MACRO}!({module}, {field});\n"
            ));
        }
        source.push_str("    }\n");
    }
    source.push_str("}\n\n");
    source
}

fn regen_openapi(root: &Path) {
    let content = fs::read_to_string(root.join(SCHEMA_PATH))
        .unwrap_or_else(|e| panic!("failed to read {SCHEMA_PATH}: {e}"));
    let schema: schemars::schema::RootSchema = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {SCHEMA_PATH} as a JSON schema: {e}"));

    // typify matches a conversion on the schema without its metadata
    // (title, description), so this one entry covers every `date-time`
    // field, including the optional ones (inside `anyOf`).
    let date_time = SchemaObject {
        instance_type: Some(InstanceType::String.into()),
        format: Some(DATE_TIME_FORMAT.to_string()),
        ..Default::default()
    };
    // `JobType` is an integer code: it compares, hashes and copies as
    // one, so the library can filter and match on it.
    let mut job_type_patch = TypeSpacePatch::default();
    for derive in JOB_TYPE_DERIVES {
        job_type_patch.with_derive(derive);
    }
    let mut settings = TypeSpaceSettings::default();
    settings
        .with_struct_builder(true)
        .with_conversion(
            date_time,
            DATE_TIME_TYPE,
            [TypeSpaceImpl::Display, TypeSpaceImpl::FromStr].into_iter(),
        )
        // Every type compares, so a program (and the tests) can compare
        // jobs, files and request bodies.
        .with_derive(ALL_TYPES_DERIVE.to_string())
        .with_patch(JOB_TYPE, &job_type_patch);
    let mut type_space = TypeSpace::new(&settings);
    type_space
        .add_root_schema(schema)
        .expect("typify failed to process the openapi schema");

    let generated = prettyplease::unparse(
        &syn::parse2::<syn::File>(type_space.to_stream())
            .expect("typify produced tokens that aren't a valid Rust file"),
    );

    let versions = versions_source(&content);
    let cmd_help = cmd_help_source(&content);
    fs::write(
        root.join(OUTPUT_PATH),
        format!("{HEADER}{versions}{cmd_help}{generated}"),
    )
    .unwrap_or_else(|e| panic!("failed to write {OUTPUT_PATH}: {e}"));

    println!("Regenerated {OUTPUT_PATH} from {SCHEMA_PATH}. Review and commit it. Do not run cargo fmt on it.");
}

/// The name of the task that regenerates `openapi.rs`.
const TASK_REGEN_OPENAPI: &str = "regen-openapi";

fn main() -> ExitCode {
    let task = std::env::args().nth(1);
    match task.as_deref() {
        Some(TASK_REGEN_OPENAPI) => {
            // This crate is in `xtask/`, so the workspace root is its parent.
            let root = Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .expect("the xtask directory has a parent");
            regen_openapi(root);
            ExitCode::SUCCESS
        }
        _ => {
            eprintln!("Usage: cargo xtask {TASK_REGEN_OPENAPI}");
            ExitCode::from(2)
        }
    }
}
